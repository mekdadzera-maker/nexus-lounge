// Translate a stored value (e.g. status "Available") with a key prefix.
// Falls back to the raw stored value when no translation exists.
export function lbl(t, prefix, value) {
  if (!value) return value;
  const key = prefix + value;
  const out = t(key);
  return out === key ? value : out;
}
